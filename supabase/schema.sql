-- ---------------------------------------------------------------------
-- refunds: a returned item logged by a Cashier/Admin/Storekeeper. Kept
-- completely separate from stock_history and does NOT touch products.qty
-- until an Admin reviews it. Accepting it (in the app) adds the qty back
-- to the product and writes a matching 'refund' row to stock_history;
-- rejecting it just closes the request out with nothing added back.
-- ---------------------------------------------------------------------
create table if not exists public.refunds (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  product_id uuid not null references public.products(id) on delete cascade,
  product_name text not null,
  qty integer not null check (qty > 0),
  reason text,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  staff text not null default 'Admin',
  requested_at timestamptz not null default now(),
  reviewed_by text,
  reviewed_at timestamptz
);

alter table public.refunds enable row level security;

create policy "refunds: owner all" on public.refunds
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "refunds: staff all" on public.refunds
  for all using (public.is_staff_of(user_id)) with check (public.is_staff_of(user_id));

create index if not exists refunds_user_idx on public.refunds(user_id);
create index if not exists refunds_status_idx on public.refunds(status);

