-- ---------------------------------------------------------------------
-- staff: employees a business owner adds, each with a PIN and role.
-- Used for "Acting As" on the Staff page so scans/adjustments are
-- attributed to a real person, not a free-text label.
-- ---------------------------------------------------------------------
create table if not exists public.staff (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  pin text not null,
  role text not null default 'Cashier' check (role in ('Admin', 'Manager', 'Cashier', 'Storekeeper')),
  -- Links to this staff member's own, independent Supabase Auth account
  -- (built from Business Code + Username + PIN — see src/staffAuth.js) so
  -- they can sign in on their own phone. Null for staff added before this
  -- was introduced — use "Set up device login" on the Staff page for them.
  auth_user_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.staff enable row level security;

create policy "staff: owner all" on public.staff
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- Lets a signed-in staff member read their OWN row right after logging
-- in (to learn their name/role/business) without seeing anyone else's.
create policy "staff: self read" on public.staff
  for select using (auth_user_id = auth.uid());

create index if not exists staff_user_idx on public.staff(user_id);
create index if not exists staff_auth_user_idx on public.staff(auth_user_id);

