-- =====================================================================
-- TallyBust — Supabase schema
-- Run this once in your project's SQL Editor (Supabase Dashboard →
-- SQL Editor → New query → paste all of this → Run).
--
-- Model: single business per authenticated Owner account, identified by
-- the auth.uid() that created it (stored as user_id on every table).
-- Staff members each get their own separate, independent Supabase Auth
-- account too (see is_staff_of() and src/staffAuth.js), but every row
-- they read or write is still scoped to their employer's user_id — they
-- never get an account of their own business. Row Level Security below
-- enforces that boundary on every table.
-- =====================================================================

create extension if not exists "uuid-ossp";

-- ---------------------------------------------------------------------
-- settings: one row per user — business name, currency
-- ---------------------------------------------------------------------
create table if not exists public.settings (
  user_id uuid primary key references auth.users(id) on delete cascade,
  business_name text not null default 'My Business',
  currency text not null default '₦',
  owner_email text,
  trial_start_date date not null default current_date,
  subscription_status text not null default 'trial' check (subscription_status in ('trial', 'active', 'expired')),
  subscription_expires_at date,
  is_admin boolean not null default false,
  -- Short, shareable code (e.g. "K3F9QX") the Owner gives to staff — it's
  -- baked into each staff member's own login so their account only ever
  -- exists for this one business. Auto-generated by a trigger below.
  business_code text unique,
  updated_at timestamptz not null default now()
);

alter table public.settings enable row level security;

create policy "settings: owner read" on public.settings
  for select using (auth.uid() = user_id);
create policy "settings: owner insert" on public.settings
  for insert with check (auth.uid() = user_id);
create policy "settings: owner update" on public.settings
  for update using (auth.uid() = user_id);

create or replace function public.generate_business_code()
returns text
language sql
as $$
  select upper(substr(md5(gen_random_uuid()::text), 1, 6));
$$;

create or replace function public.set_business_code()
returns trigger
language plpgsql
as $$
begin
  if new.business_code is null then
    loop
      new.business_code := public.generate_business_code();
      exit when not exists (select 1 from public.settings where business_code = new.business_code);
    end loop;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_set_business_code on public.settings;
create trigger trg_set_business_code
  before insert on public.settings
  for each row execute function public.set_business_code();

-- is_admin() is used below and by the app's admin dashboard
create or replace function public.is_admin()
returns boolean
language sql
security definer
stable
as $$
  select coalesce((select is_admin from public.settings where user_id = auth.uid()), false);
$$;

create policy "settings: admin read all" on public.settings
  for select using (public.is_admin());
create policy "settings: admin update all" on public.settings
  for update using (public.is_admin());

-- is_staff_of() — true if the signed-in user is a staff member (their own,
-- independent Supabase Auth account, linked via staff.auth_user_id) of the
-- business owned by `business_owner`. Used throughout so a staff member's
-- own phone can sign in and work with their employer's data directly,
-- without ever sharing the Owner's login.
create or replace function public.is_staff_of(business_owner uuid)
returns boolean
language sql
security definer
stable
as $$
  select exists (
    select 1 from public.staff
    where user_id = business_owner and auth_user_id = auth.uid()
  );
$$;

create policy "settings: staff read" on public.settings
  for select using (public.is_staff_of(user_id));

-- ---------------------------------------------------------------------
-- products
-- ---------------------------------------------------------------------
create table if not exists public.products (
  id uuid primary key default uuid_generate_v4(),
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  category text not null default 'Uncategorized',
  sku text not null,
  qty integer not null default 0,
  min_stock integer not null default 0,
  purchase_price numeric(12,2) not null default 0,
  selling_price numeric(12,2) not null default 0,
  supplier text,
  expiry date,
  batch text,
  -- Unit-sale fields: lets a pack-stocked item (e.g. a box of tablets)
  -- also be sold one loose unit at a time. See migration_v6_unit_sales.sql
  -- for the full explanation of how loose_units is kept in sync.
  unit_sale_enabled boolean not null default false,
  unit_name text,
  unit_qty_per_pack integer not null default 0,
  unit_price numeric(12,2) not null default 0,
  loose_units integer not null default 0,
  created_at timestamptz not null default now(),
  deleted_at timestamptz,
  unique (user_id, sku)
);

alter table public.products enable row level security;

create policy "products: owner read" on public.products
  for select using (auth.uid() = user_id);
create policy "products: owner insert" on public.products
  for insert with check (auth.uid() = user_id);
create policy "products: owner update" on public.products
  for update using (auth.uid() = user_id);
create policy "products: owner delete" on public.products
  for delete using (auth.uid() = user_id);
create policy "products: admin read all" on public.products
  for select using (public.is_admin());
create policy "products: staff read" on public.products
  for select using (public.is_staff_of(user_id));
create policy "products: staff insert" on public.products
  for insert with check (public.is_staff_of(user_id));
create policy "products: staff update" on public.products
  for update using (public.is_staff_of(user_id));

create index if not exists products_user_idx on public.products(user_id);

-- ---------------------------------------------------------------------
-- stock_history: every Stock In / Stock Out (sale) / Refund event.
-- 'count' is kept in the check constraint only so older rows recorded
-- before Stock Count was removed from the app remain valid — the app
-- itself no longer writes that type.
-- ---------------------------------------------------------------------
create table if not exists public.stock_history (
  id uuid primary key default uuid_generate_v4(),
  user_id uuid not null references auth.users(id) on delete cascade,
  product_id uuid not null references public.products(id) on delete cascade,
  product_name text not null,
  type text not null check (type in ('stock-in', 'sale', 'count', 'unit-sale', 'refund')),
  qty integer not null,
  unit_price numeric(12,2) not null default 0,
  staff text not null default 'Admin',
  occurred_on date not null default current_date,
  captured_photo text,
  created_at timestamptz not null default now()
);

alter table public.stock_history enable row level security;

create policy "history: owner read" on public.stock_history
  for select using (auth.uid() = user_id);
create policy "history: owner insert" on public.stock_history
  for insert with check (auth.uid() = user_id);
create policy "history: admin read all" on public.stock_history
  for select using (public.is_admin());
create policy "history: staff read" on public.stock_history
  for select using (public.is_staff_of(user_id));
create policy "history: staff insert" on public.stock_history
  for insert with check (public.is_staff_of(user_id));

create index if not exists stock_history_user_idx on public.stock_history(user_id);
create index if not exists stock_history_product_idx on public.stock_history(product_id);
create index if not exists stock_history_date_idx on public.stock_history(occurred_on);

